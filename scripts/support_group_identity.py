#!/usr/bin/env python3
"""Off-mode gate for support groups.

docs/superpowers/plans/2026-09-02-support-sets-and-groups.md §3.7.

TWO GATES, and the default is the tolerance one:

  --gate tolerance  (default) run each pair of G-code files through the fork's own Slice
                    Compare engine and require: zero changed config rows, zero changed layers,
                    zero layers present on only one side, and at least --segment-tolerance per
                    cent of segments matching (default 99.0).

                    The plan asked for 100 % of segments. The BASELINE CANNOT MEET THAT AGAINST
                    ITSELF: running this script with one executable on both sides still shows a
                    handful of segments (10-18 out of several thousand, on 4-7 layers of a 41-66
                    layer print) appearing or vanishing in roughly one case per run. The
                    structural criteria - config rows, changed layers, added or removed layers -
                    ARE stable at zero, so they are required exactly, and the segment count is
                    thresholded instead. A support-group regression would move layers or a large
                    fraction of segments, not 0.4 % of them; classic tree support, which really
                    does move (see below), lands at 6 %.
                    The engine is reached through tests/slice_compare_cli, a test-only
                    executable calling SliceCompare::load_snapshot_from_file and the diff_*
                    functions directly - nothing was added to the shipped application.
  --gate bytes      the original byte comparison, described below. Kept for the day the
                    determinism fix lands; it does NOT pass on this tree.
  --gate groups     the ON-mode gate, added in Stage 3. It runs ONLY the corpus cases marked
                    "groups": true - the ones whose parts actually carry support_group data -
                    and inverts the question: each one must DIFFER from the baseline, because the
                    baseline ignores the groups and the candidate honours them. It also requires
                    zero changed CONFIG rows, so the difference is provably geometry and not a
                    settings change, and where a case names "expect_tool" it requires that tool
                    change to appear in the candidate's G-code and NOT in the baseline's.

The two default gates (tolerance, bytes) SKIP the "groups": true cases, for the same reason:
from Stage 3 on those cases are meant to differ. Off mode - every project that carries no
support_group data, plus any where every part resolves to the same support config - is what the
tolerance gate covers, and it is the hard gate.

Why the default moved: the plan's own 5.1 experiment - run this script with the SAME
executable on both sides - showed that about a third of same-binary comparisons differ by a
block of roughly 40 extrusion lines. That is not support-specific (a no-support control
differs too), it survives pinning to one CPU and it survives disabling Arachne. Byte identity
is therefore not an acceptance criterion this codebase can meet today. The tolerance gate
still catches everything a support-group change could cause: any layer whose extrusion,
timing or footprint moved, and any segment that appeared, vanished or shifted.

Slices every case of tests/data/support_corpus/corpus.json with two builds of the slicer and
compares the G-code byte for byte, after normalising two things and nothing else - not the config
block, not layer counts, not a single extrusion coordinate:

  1. the `; generated by <version> on <local timestamp>` header (src/libslic3r/GCode.cpp:2275);
  2. the `id:<N>` token of the `; printing object <name> id:<N> copy <n>` comment family
     (GCode.cpp:6651, :6724, :6840, :6995 and the "unique label id:" variants).

(2) is a deviation from the plan's §3.7, which asks for one normalised line. It is forced, and the
plan's own §5.1 experiment is what forced it: running this script with the SAME executable on both
sides shows that token differing between two runs of one binary as soon as the plate holds more
than one object (`id:0` vs `id:9223578746636304929`). It is ModelObject::id(), a process-global
ObjectID counter used only to label the object-exclusion comments - a name, never geometry. Every
coordinate stays strictly compared. Cases with a single object are reproducible without it.

SINGLE CORE IS MANDATORY, and is the other thing 5.1 found. On all cores the slicer is simply
not self-reproducible when it generates support: roughly a third of runs of ONE binary on ONE
project differ from the previous run, in extrusion coordinates and sometimes in whole blocks,
and classic tree support varied by a thousand G-code lines between runs. Pinning the process to
one CPU makes TBB run a single thread (Thread.cpp:222 sizes the arena from
tbb::this_task_arena::max_concurrency(), which honours the affinity mask) and the output becomes
stable. This script therefore pins its own affinity before spawning anything and the slicer
inherits it. --all-cores turns that off, and is only useful to demonstrate the nondeterminism.

    python scripts/support_group_identity.py --baseline <old exe> --candidate <new exe> \
           --corpus tests/data/support_corpus --out <dir> [--datadir <isolated dd>]

Pass the same executable twice to run the plan's §5.1 experiment - "is the corpus reproducible at
all?" - before trusting any later comparison.

Exits non-zero on the first difference, naming the first differing line. Always pass --datadir so
the run cannot touch a real profile tree.
"""
